// Wraps avatar image(s) into a .js file as data URL(s), so the demo works when
// opened straight from disk (file://) without a web server.
//
//   node scripts/image-to-js.mjs avatars/kimono/avatar.jpg kimono avatars/kimono/image.js [avatars/kimono/avatar_rest.jpg]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { extname } from 'node:path';

const [input, name, output, restArg] = process.argv.slice(2);
if (!input || !name || !output) {
  console.error('usage: node scripts/image-to-js.mjs <image> <avatar-name> <output.js> [rest-image]');
  process.exit(1);
}

const getMime = (file) => ({ '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' }[extname(file).toLowerCase()]);

const mime = getMime(input);
if (!mime) {
  console.error(`unsupported image type: ${input}`);
  process.exit(1);
}

const restInput = restArg || input.replace(/(\.[^.]+)$/, '_rest$1');
const hasRest = existsSync(restInput);

const dataUrlWave = `data:${mime};base64,${readFileSync(input).toString('base64')}`;
let js = '';

if (hasRest) {
  const mimeRest = getMime(restInput);
  const dataUrlRest = `data:${mimeRest};base64,${readFileSync(restInput).toString('base64')}`;
  js = `// Generated from ${input} and ${restInput}. Do not edit by hand.
(function (root) {
  var urlWave = ${JSON.stringify(dataUrlWave)};
  var urlRest = ${JSON.stringify(dataUrlRest)};
  if (typeof module === 'object' && module.exports) module.exports = { wave: urlWave, rest: urlRest };
  else {
    var reg = (root.VoiceProjectionImages = root.VoiceProjectionImages || {});
    reg[${JSON.stringify(name)}] = urlWave;
    reg[${JSON.stringify(name + '_rest')}] = urlRest;
  }
})(typeof self !== 'undefined' ? self : this);
`;
} else {
  js = `// Generated by scripts/image-to-js.mjs from ${input}. Do not edit by hand.
(function (root) {
  var url = ${JSON.stringify(dataUrlWave)};
  if (typeof module === 'object' && module.exports) module.exports = url;
  else (root.VoiceProjectionImages = root.VoiceProjectionImages || {})[${JSON.stringify(name)}] = url;
})(typeof self !== 'undefined' ? self : this);
`;
}

writeFileSync(output, js);
console.log(`wrote ${output} (${(js.length / 1024).toFixed(0)} KB)`);
