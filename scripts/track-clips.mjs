// Follows her face through every frame of every clip (in headless Chrome) and saves the
// result, so the talking mouth always sits exactly on her lips.
//
//   node scripts/track-clips.mjs avatars/kimono/clips kimono
//
// Writes <clips-folder>/tracks.js. Needs Google Chrome installed.
import { spawn } from 'node:child_process';
import { mkdtempSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, extname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [dir, avatar, fpsArg] = process.argv.slice(2);
if (!dir || !avatar) {
  console.error('usage: node scripts/track-clips.mjs <clips-folder> <avatar-name> [fps]');
  process.exit(1);
}
const fps = Number(fpsArg) || 30;
const chromePaths = [
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
];
const chromePath = chromePaths.find((p) => existsSync(p));
if (!chromePath) {
  console.error('Google Chrome not found.');
  process.exit(1);
}

const clips = {};
for (const file of readdirSync(dir)) {
  if (!/\.(mp4|m4v|webm)$/i.test(file)) continue;
  clips[basename(file, extname(file)).toLowerCase()] = pathToFileURL(resolve(dir, file)).href;
}

const port = 9400 + Math.floor(Math.random() * 400);
const profile = mkdtempSync(join(tmpdir(), 'vp-track-'));
const chrome = spawn(chromePath, ['--headless=new', '--allow-file-access-from-files', `--remote-debugging-port=${port}`, `--user-data-dir=${profile}`, 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

try {
  let target;
  for (let i = 0; i < 100 && !target; i++) {
    try { target = (await (await fetch(`http://127.0.0.1:${port}/json`)).json()).find((t) => t.type === 'page'); } catch {}
    if (!target) await sleep(200);
  }
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((r) => ws.addEventListener('open', r));
  let id = 0;
  const pending = new Map();
  ws.addEventListener('message', (e) => {
    const m = JSON.parse(e.data);
    if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); }
  });
  const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });

  await send('Page.enable');
  await send('Page.navigate', { url: pathToFileURL(resolve('scripts/track-clips.html')).href });
  await sleep(1500);
  console.log(`tracking ${Object.keys(clips).join(', ')} at ${fps} fps…`);
  const res = await send('Runtime.evaluate', {
    expression: `run(${JSON.stringify(clips)}, ${JSON.stringify(avatar)}, ${fps})`,
    awaitPromise: true,
    returnByValue: true,
  });
  if (res.result.exceptionDetails) throw new Error(JSON.stringify(res.result.exceptionDetails));
  const tracks = res.result.result.value;
  for (const [name, t] of Object.entries(tracks)) {
    const confs = t.frames.map((f) => f[4]);
    const low = confs.filter((c) => c < 0.6).length;
    console.log(`  ${name}: ${t.frames.length} frames, face not clear in ${low}`);
  }
  const js = `// Generated by scripts/track-clips.mjs. Do not edit by hand.
// Per clip: mouth position in every frame: [x, y, turn (rad), size, confidence].
(function (root) {
  var all = (root.VoiceProjectionTracks = root.VoiceProjectionTracks || {});
  all[${JSON.stringify(avatar)}] = ${JSON.stringify(tracks)};
})(typeof self !== 'undefined' ? self : this);
`;
  writeFileSync(join(dir, 'tracks.js'), js);
  console.log(`wrote ${join(dir, 'tracks.js')} (${(js.length / 1024).toFixed(0)} KB)`);
  ws.close();
} finally {
  chrome.kill();
}
